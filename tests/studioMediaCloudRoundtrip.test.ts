import 'fake-indexeddb/auto';
import test from 'node:test';
import assert from 'node:assert/strict';
import { MemoryManager } from '../managers.js';
import { RoomManager } from '../roomManager.js';
import { SupabaseCloudSyncManager } from '../supabaseCloudSync.js';
import { persistStudioImage,persistStudioVideo,deleteSavedStudioImage,deleteSavedStudioVideo,getSavedStudioImage,getSavedStudioVideo,readStudioImageMetadata,readStudioVideoMetadata,STUDIO_MEDIA_KEY } from '../studioMediaStore.js';
import type {ImageReceipt} from '../vpsImageJob.js';
import type {PersistedVideoJob} from '../videoStudioPersistence.js';
test('existing cloud media projection and mock download roundtrip studio metadata without live cloud calls',async()=>{
 const map=new Map<string,string>();
 Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(k:string)=>map.get(k)??null,setItem:(k:string,v:string)=>map.set(k,v),removeItem:(k:string)=>map.delete(k)}});
 const r:ImageReceipt={version:1,jobId:'12345678-1234-4234-8234-123456789ab9',prompt:'Synthetic lake',modelName:'Qwen Image 3',aspectRatio:'16:9',seed:99,createdAt:123};
 const j:PersistedVideoJob={version:1,model:'wan-2-7-enhanced-text-to-video',modelName:'Wan',queueId:'fixture-roundtrip',prompt:'Synthetic clouds',mode:'text-to-video',queuedAt:124};
 const a=await persistStudioImage(r,new Blob([new Uint8Array(1024).fill(7)],{type:'image/webp'}));
 const b=await persistStudioVideo(j,new Blob([new Uint8Array(2048).fill(5)],{type:'video/mp4'}));
 const sync=new SupabaseCloudSyncManager(new MemoryManager(),new RoomManager(),{onStateChange:()=>undefined,onRemoteApplied:()=>undefined}) as any;
 const rows=(await sync.collectLocalMedia([],'fixture-user')).filter((row:any)=>row.conversation_key===STUDIO_MEDIA_KEY);
 assert.equal(rows.length,2);
 const photo=rows.find((row:any)=>row.kind==='character_photo'),video=rows.find((row:any)=>row.kind==='attachment');
 assert.equal(photo.metadata.studio.seed,99);assert.equal(video.metadata.studio.prompt,j.prompt);
 assert.equal(readStudioImageMetadata('unrelated',a.id,a.studio),undefined);
 assert.equal(readStudioVideoMetadata(STUDIO_MEDIA_KEY,b.id,{...b.studio,queueId:'different'}),undefined);
 const blobs=new Map(rows.map((row:any)=>[row.storage_path,row.blob]));
 await deleteSavedStudioImage(a.id);await deleteSavedStudioVideo(b.id);
 sync.client={storage:{from:()=>({download:async(path:string)=>({data:blobs.get(path),error:null})})}};
 await sync.pullMedia(rows);
 const recoveredPhoto=await getSavedStudioImage(r),recoveredVideo=await getSavedStudioVideo(j);
 assert.equal(recoveredPhoto?.studio?.seed,99);assert.equal(recoveredVideo?.studio?.prompt,j.prompt);
 assert.equal(recoveredPhoto?.blob.size,a.blob.size);assert.equal(recoveredVideo?.blob.size,b.blob.size);
 const projected=await sync.collectLocalMedia([],'fixture-user');
 for(const row of rows)assert.equal(projected.find((x:any)=>x.asset_id===row.asset_id)?.signature,row.signature);
});
